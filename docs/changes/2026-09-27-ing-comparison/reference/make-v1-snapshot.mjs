// Generates src/engine/__tests__/v1RowSnapshot.js: a bit-exact row snapshot of the v1 engine BEFORE the
// burn-share extension, used by ingInvariants.test.js to prove that φ = 1 reproduces v1 row for row (spec R1).
// Not a golden value. Run against a checkout of the pre-change commit:
//   git worktree add /tmp/v1 4c13019 && node make-v1-snapshot.mjs /tmp/v1 > <repo>/src/engine/__tests__/v1RowSnapshot.js
// Scenarios: the v1 golden fixtures A–H with every swap year, plus three invariants scenarios (full mortality,
// discount at death, non-neutral consideration). Inputs use the ORIGINAL v1 BASE (no ING fields).
import { pathToFileURL } from 'node:url';

const root = process.argv[2];
if (!root) { console.error('usage: node make-v1-snapshot.mjs <path-to-v1-checkout>'); process.exit(2); }
const load = (p) => import(pathToFileURL(`${root}/${p}`).href);
const { simulate, evaluateAsset } = await load('src/engine/idgtModel.js');
const { lxColumn } = await load('src/engine/mortality.js');
const { SSA_2021_LX } = await load('src/data/mortalityTable.js');
const { BASE, FIXTURES } = await load('src/engine/__tests__/fixtures.js');
const male = lxColumn(SSA_2021_LX, 'male');

const scenarios = [
  ...Object.entries(FIXTURES).map(([k, inp]) => ({ name: `Fixture ${k}`, inp, swaps: 'all' })),
  { name: '65M full mortality, $20M estate', inp: { ...BASE, deathYearOverride: null, lx: male, age: 65 }, swaps: [0, 7] },
  { name: 'discount at death', inp: { ...BASE, delta: 0.3, discountAtDeath: true }, swaps: [0, 2] },
  { name: 'non-neutral swap (8% growth consideration)', inp: { ...BASE, deathYearOverride: null, lx: male, age: 70, gSw: 0.08, ySw: 0, tauSw: 0 }, swaps: [5] },
];

let keys = null;
const out = [];
for (const sc of scenarios) {
  const N = evaluateAsset(sc.inp).derived.N;
  const swaps = sc.swaps === 'all' ? Array.from({ length: N + 1 }, (_, i) => i) : sc.swaps;
  for (const s of swaps) {
    const sim = simulate(sc.inp, s, N);
    if (!keys) keys = Object.keys(sim.rows[0]);
    out.push({ name: sc.name, s, N, infeasible: sim.infeasible, rows: sim.rows });
  }
}
console.log(`// GENERATED by docs/changes/2026-09-27-ing-comparison/reference/make-v1-snapshot.mjs from the v1 engine
// (commit 4c13019, before the burn-share extension). Bit-exact rows of simulate(inp, s, N); not golden values.
// Scenario inputs are defined in the generator. Regenerate only if the v1 contract itself changes.
/* eslint-disable */
export const V1_ROW_KEYS = ${JSON.stringify(keys)};
export const V1_SNAPSHOT = ${JSON.stringify(out)};`);
